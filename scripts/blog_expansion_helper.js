function expandBlogContent(content, category, title = "") {
  const words = content.trim().split(/\s+/).filter(w => w.length > 0);
  if (words.length >= 300) {
    return content;
  }

  // Determine key category mappings
  const cat = (category || "").trim();
  let template = templates[cat];

  // Try partial mapping or fallbacks
  if (!template) {
    if (cat.includes("SEO") || cat.includes("Search")) {
      template = templates["SEO"];
    } else if (cat.includes("Sale") || cat.includes("Conversion") || cat.includes("CRO")) {
      template = templates["Sales"];
    } else if (cat.includes("Development") || cat.includes("Coding") || cat.includes("Tech") || cat.includes("Programming")) {
      template = templates["Web Development"];
    } else if (cat.includes("Design") || cat.includes("UI") || cat.includes("UX")) {
      template = templates["Web Design"];
    } else if (cat.includes("Brand") || cat.includes("Identity")) {
      template = templates["Branding"];
    } else if (cat.includes("Social") || cat.includes("Video")) {
      template = templates["Social Media"];
    } else if (cat.includes("Ad") || cat.includes("Paid") || cat.includes("Performance")) {
      template = templates["Performance Marketing"];
    } else {
      template = templates["Marketing"]; // fallback to general Marketing
    }
  }

  return content.trim() + template;
}

module.exports = {
  expandBlogContent,
  templates
};
